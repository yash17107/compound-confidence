export function readLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE);
    if (LANGS.some((item) => item.id === saved)) return saved;
  } catch {
    /* ignore */
  }
  return "en";
}

export function saveLang(id) {
  try {
    localStorage.setItem(LANG_STORAGE, id);
  } catch {
    /* ignore */
  }
}

export function fill(template, vars = {}) {
  return String(template || "").replace(/\{(\w+)\}/g, (match, key) =>
    key in vars ? String(vars[key]) : match,
  );
}

export function langMeta(id) {
  return LANGS.find((item) => item.id === id) || LANGS[0];
}

